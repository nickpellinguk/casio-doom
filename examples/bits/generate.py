# Encodes the BBC Micro Trogg and Scrubbly sprites (their black pixels) as
# one or two numbers per column, and writes sprites.fx, which draws them
# with the bit renderer (render.fx).
#
# Usage:  python3 examples/bits/generate.py [path/to/steamfrak]
# (default ../steamfrak, next to this repository)
import os, sys
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
STEAMFRAK = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', '..', 'steamfrak')
H = 21   # bits per number: halving stays exact well beyond this

def columns(sprite):
    im = Image.open(os.path.join(STEAMFRAK, 'assets', 'sprites', sprite)).convert('RGBA')
    w, h = im.size
    cols = []
    for x in range(w):
        bits = 0
        for k in range(h):                     # bit k = k rows up from the bottom
            r, g, b, a = im.getpixel((x, h - 1 - k))
            if a and r < 50 and g < 50 and b < 50:
                bits |= 1 << k
        cols.append((bits & ((1 << H) - 1), bits >> H))
    return cols, w, h

out = ['# The Trogg and a Scrubbly at their full BBC Micro size, drawn by the bit',
       '# renderer (Prog 4) from one or two numbers per column.',
       '# Each number is a column of dots in binary, lowest bit at the bottom:',
       '# N holds the bottom 21 rows and M the rows above.',
       '# Generated by generate.py from the sprites in steamfrak.',
       'Range 1,95,0,1,63,0', 'Cls', f'{H}→H:3→C']
for label, sprite, x0 in (('the Trogg', 'sTrogg_sr_Beeb.png', 12), ('a Scrubbly', 'sScrubbly_Beeb.png', 50)):
    cols, w, h = columns(sprite)
    out.append(f'# {label}: {w} columns, {h} rows')
    out.append(f'{x0}→A')
    for lo, hi in cols:
        out.append(f'{lo}→N:{hi}→M:Prog 4')
out.append('# show the picture (y=0 is off-screen, so nothing else is drawn)')
out.append('Graph Y=0')
open(os.path.join(HERE, 'sprites.fx'), 'w').write('\n'.join(out) + '\n')
print('\n'.join(out))
